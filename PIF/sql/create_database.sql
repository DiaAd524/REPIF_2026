DROP DATABASE IF EXISTS pif;
CREATE DATABASE pif CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE pif;

-- =========================== 1. TABLES ===============================

CREATE TABLE PIF_User (
  idUser               INT          NOT NULL AUTO_INCREMENT,
  Username             VARCHAR(13)  NOT NULL,
  Email                VARCHAR(255) NOT NULL,
  PhoneNumber          VARCHAR(20)  NOT NULL,
  UserPassword         VARCHAR(255) NOT NULL,              
  PowercellBalance     INT          NOT NULL DEFAULT 0,
  RegistrationDate     DATE         NOT NULL,
  IsAdmin              BOOLEAN      NOT NULL DEFAULT FALSE,
  PRIMARY KEY (idUser),
  UNIQUE (Username),
  UNIQUE (Email)
);

CREATE TABLE PIF_Locations (
  idLocation           INT          NOT NULL AUTO_INCREMENT,
  LocationName         VARCHAR(100) NOT NULL,
  LocationAddress      VARCHAR(100) NOT NULL,
  LocationDescription  TEXT         NOT NULL,
  Photo                VARCHAR(255) NULL,
  PRIMARY KEY (idLocation)
);

CREATE TABLE PIF_ChargingStation (
  idChargingStation    INT          NOT NULL AUTO_INCREMENT,
  idLocation           INT          NOT NULL,              -- foreign key -> PIF_Locations
  StationName          VARCHAR(100) NOT NULL,
  StationDescription   TEXT         NOT NULL,
  IpAddress            VARCHAR(45)  NOT NULL,              
  PRIMARY KEY (idChargingStation)
);

CREATE TABLE PIF_Port (
  idPort               INT          NOT NULL AUTO_INCREMENT,
  idChargingStation    INT          NOT NULL,              -- foreign key -> PIF_ChargingStation
  PortNumber           INT          NOT NULL,
  PortType             VARCHAR(10)  NOT NULL,              -- USB-C, USB-A, Micro-USB
  PRIMARY KEY (idPort),
  UNIQUE (idChargingStation, PortNumber)                   
);

CREATE TABLE PIF_Activation (
  idActivation         INT          NOT NULL AUTO_INCREMENT,
  idUser               INT          NOT NULL,              -- foreign key -> PIF_User
  idPort               INT          NOT NULL,              -- foreign key -> PIF_Port
  StartDateTime        DATETIME     NOT NULL,
  DurationMinutes      INT          NOT NULL,
  Success              BOOLEAN      NOT NULL,              
  PRIMARY KEY (idActivation)
);

CREATE TABLE PIF_Purchase (
  idPurchase           INT          NOT NULL AUTO_INCREMENT,
  idUser               INT          NOT NULL,              -- foreign key -> PIF_User
  PurchaseDateTime     DATETIME     NOT NULL,
  AmountEuro           DECIMAL(8,2) NOT NULL,
  Powercells           INT          NOT NULL,
  PRIMARY KEY (idPurchase)
);

-- ======================== 2. FOREIGN KEYS ============================

ALTER TABLE PIF_ChargingStation
  ADD CONSTRAINT fk_ChargingStation_Locations
  FOREIGN KEY (idLocation) REFERENCES PIF_Locations (idLocation);

ALTER TABLE PIF_Port
  ADD CONSTRAINT fk_Port_ChargingStation
  FOREIGN KEY (idChargingStation) REFERENCES PIF_ChargingStation (idChargingStation);

ALTER TABLE PIF_Activation
  ADD CONSTRAINT fk_Activation_User
  FOREIGN KEY (idUser) REFERENCES PIF_User (idUser);

ALTER TABLE PIF_Activation
  ADD CONSTRAINT fk_Activation_Port
  FOREIGN KEY (idPort) REFERENCES PIF_Port (idPort);

ALTER TABLE PIF_Purchase
  ADD CONSTRAINT fk_Purchase_User
  FOREIGN KEY (idUser) REFERENCES PIF_User (idUser);

